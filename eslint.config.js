import gts from 'gts/build/src/index.js';

/**
 * ESLint flat config for switchback.
 *
 * The rule set is gts's (Google TypeScript Style) end to end. Three things are
 * adjusted, all because this repo predates gts and has a house style gts's
 * defaults would rewrite wholesale:
 *
 *  - **Type-aware rules need a tsconfig that contains the linted file.** gts
 *    points at `./tsconfig.json`, and the repo's own gate uses that file too
 *    (see `packages/pi/AGENTS.md` -> Verification). Lint coverage must not
 *    depend on which files the gate happens to include, so the parser is
 *    retargeted at `tsconfig.eslint.json`, which widens the include to
 *    `packages/**` and `tests/`. `TYPE_AWARE_ENTRY` below is gts's own
 *    type-aware entry, addressed by position so the rule set itself stays gts's.
 *  - **Quotes and unused-underscore params.** gts enforces single quotes and
 *    flags every `_`-prefixed binding as dead code; this codebase uses double
 *    quotes throughout (170 double-quoted assignments vs 2 single) and marks
 *    intentionally-unused bindings with a leading underscore. Both overrides
 *    live INSIDE gts's own type-aware entry rather than in a standalone config
 *    object, because a bare object carrying a `@typescript-eslint/*` rule
 *    raises "could not find plugin" for any file the TypeScript entry does not
 *    cover — which is how `site/` (generated by `mkdocs build`, 36 `.js`
 *    files) broke the gate until `site/**` was ignored. `quotes` agreeing with
 *    Prettier also stops the two tools fighting each other.
 *
 * Formatting options are deliberately *not* set here beyond the quotes rule.
 * eslint-plugin-prettier resolves each file's nearest Prettier config, so the
 * repo's `.prettierrc.json` governs: it keeps the house style (tabs, 120
 * columns, double quotes, existing line endings) rather than gts's defaults
 * (2 spaces, 80 columns, single quotes, LF), which would reformat every file in
 * the tree for no gain.
 *
 * This file is ESM because package.json sets `"type": "module"`; gts is CommonJS,
 * so its config array arrives as the default import.
 *
 * `gts lint` and `gts fix` (mise tasks `lint-ts` / `format-ts`) run this.
 */
const TYPE_AWARE_ENTRY = 7;

export default [
  {
    ignores: [
      '.git/**',
      '.beads/**',
      'node_modules/**',
      'dist/**',
      'coverage/**',
      // Generated docs output (`mkdocs build`), gitignored but still on disk.
      'site/**',
      // Machine-local skill catalog (gitignored): third-party `.mjs`/`.ts`
      // bundles that no repo change can fix. Linting them buried every real
      // finding, so the gate covers the repo's own sources only.
      '.agents/**',
      'eslint.config.js',
    ],
  },
  ...gts.map((entry, index) =>
    index === TYPE_AWARE_ENTRY
      ? {
          ...entry,
          languageOptions: {
            ...entry.languageOptions,
            parserOptions: { ...entry.languageOptions.parserOptions, project: './tsconfig.eslint.json' },
          },
          rules: {
            ...entry.rules,
            quotes: ['warn', 'double', { avoidEscape: true }],
            // A leading underscore means "intentionally unused" (test fixture
            // params, ignored callback args). Without this, gts reports every
            // one of them as dead code.
            '@typescript-eslint/no-unused-vars': [
              'error',
              {
                argsIgnorePattern: '^_',
                varsIgnorePattern: '^_',
                caughtErrorsIgnorePattern: '^_',
                destructuredArrayIgnorePattern: '^_',
              },
            ],
          },
        }
      : entry,
  ),
  {
    // Repo scripts (`scripts/`) are Node ESM, which gts's JavaScript entry does
    // not configure: it assumes no Node runtime (so `console`/`process` read as
    // undefined) and enforces single quotes, while Prettier — via
    // `.prettierrc.json` — wants double. This block sits LAST so it wins, and
    // the two tools settle instead of deadlocking, which is what `--fix` needs
    // to rewrite a string literal at all.
    files: ['scripts/**/*.mjs'],
    languageOptions: {
      globals: { console: 'readonly', process: 'readonly' },
    },
    rules: {
      quotes: ['warn', 'double', { avoidEscape: true }],
    },
  },
];
